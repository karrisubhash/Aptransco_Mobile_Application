# Line inspection — who may record an inspection
# ---------------------------------------------------------------------------
# When on (the default), ANY authenticated employee may record an inspection on
# any tower, instead of only the towers an EE granted them via a RoleAssignment.
#
# Open access is a deliberate operational choice. The read scope is already
# wider than the old capture scope — a supervisor sees their whole oversight
# subtree and management sees every subdivision — so in practice this lets
# people inspect what they can already see. It also unblocks the case that made
# the old rule untenable: an employee with no RoleAssignment row could inspect
# nothing at all, because visible_lines() returns an empty queryset for them.
#
# Scope of this flag — it governs RECORDING AN INSPECTION only:
#   * closing a defect ticket keeps its own supervisory scoping (api/views.py)
#   * every read / oversight queryset (viewing.py) is untouched
#   * the GPS proof-of-presence gate is untouched and still applies
#
# Set LINE_INSPECTION_OPEN_INSPECT=0 to restore per-assignment scoping; the
# original logic is intact in jurisdiction.can_edit_tower and still tested.
LINE_INSPECTION_OPEN_INSPECT = os.environ.get('LINE_INSPECTION_OPEN_INSPECT', '1') != '0'
