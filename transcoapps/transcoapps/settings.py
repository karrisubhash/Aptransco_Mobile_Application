def _load_local_env():
    """Load BASE_DIR/.env.local (gitignored, never committed) into
    os.environ, if present. Runs here — the very first thing settings.py
    does — so it applies no matter how the server process gets started
    (integrated terminal, a separate terminal that never sourced anything,
    an IDE's Run/Debug button, a task runner, etc). Dot-sourcing a shell
    script only sets env vars in that one shell session; this doesn't have
    that gap."""
    env_file = BASE_DIR / '.env.local'
    if not env_file.exists():
        return
    for line in env_file.read_text(encoding='utf-8').splitlines():
        line = line.strip()
        if not line or line.startswith('#') or '=' not in line:
            continue
        key, _, value = line.partition('=')
        os.environ.setdefault(key.strip(), value.strip())


_load_local_env()
